export function page(title: string, body: string): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>${CSS}</style>
</head>
<body><main>
${body}
<footer>Generated by the apex CLI from register state. All entities and figures in the demo are simulated.</footer>
</main></body>
</html>
`;
}

export function tile(k: string, v: string, cls = ""): string {
  return `<div class="tile"><div class="k">${esc(k)}</div><div class="v ${cls}">${v}</div></div>`;
}
