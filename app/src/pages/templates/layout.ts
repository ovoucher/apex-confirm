/** Shared HTML shell and helpers for the static pages. Plain HTML and CSS, no framework. */

export function esc(s: string | number | bigint): string {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

